def legal(name):
    """Impressum and Datenschutz: the text lives in content/legal/<name>.html, with slots for the credits and dates."""
    src = read(f'content/legal/{name}.html')
    credits_de, credits_en = [], []
    for p in PARTNERS:
        shown = partner_credits(p)
        if not shown:
            continue
        line = '; '.join(e(credit_text(c)) for c in shown)
        credits_de.append(f'<li>{e(p["name"])}: {line}</li>')
        credits_en.append(f'<li>{e(p["name"])}: {line}</li>')
    for p in PLACES:
        im = p.get('image') or {}
        if not im.get('license'):
            continue
        origin = f'<a href="{a(im["source_url"])}" rel="noopener">{e(im.get("source_name", "Wikimedia Commons"))}</a>'
        lic = f'<a href="{a(im["license_url"])}" rel="noopener">{e(im["license"])}</a>'
        same_de = '; die bearbeitete Fassung steht unter derselben Lizenz' if 'SA' in im['license'] else ''
        same_en = '; the adapted version is available under the same licence' if 'SA' in im['license'] else ''
        credits_de.append(f'<li>{e(p["name"])}: Foto von {e(im["credit"])}, {origin}, Lizenz {lic}; Ausschnitt und Größe angepasst{same_de}.</li>')
        credits_en.append(f'<li>{e(p["name"])}: photo by {e(im["credit"])}, {origin}, licence {lic}; cropped and resized{same_en}.</li>')
    for c in SITE['credits_de']:
        credits_de.append(f'<li>{e(c)}</li>')
    slots = {
        'credits_de': '<ul>' + ''.join(credits_de) + '</ul>',
        'credits_en': '<ul>' + ''.join(credits_en) + '</ul>',
        'impressum_stand': e(SITE['impressum_stand']),
        'datenschutz_stand_en': e(SITE['datenschutz_stand']['en']),
        'datenschutz_stand_de': e(SITE['datenschutz_stand']['de']),
    }
    used = set(re.findall(r'\{\{(\w+)\}\}', src))
    unknown = used - set(slots)
    if unknown:
        raise BuildError(f'content/legal/{name}.html: unknown slot(s) {sorted(unknown)}')
    body = re.sub(r'\{\{(\w+)\}\}', lambda m: slots[m.group(1)], src).rstrip('\n')
    if name == 'impressum':
        return page('impressum.html', 'Impressum / Imprint — EverFlow Experience',
                    'Impressum (Anbieterkennzeichnung nach § 5 DDG) von EverFlow Experience, München. Imprint / legal notice.',
                    body, lang='de', index=False)
    return page('datenschutz.html', 'Datenschutzerklärung / Privacy Policy — EverFlow Experience',
                'Privacy policy (Datenschutzerklärung) of EverFlow Experience, Munich: what personal data we process, why, how long, and your rights under the GDPR.',
                body, lang='en', index=False)


