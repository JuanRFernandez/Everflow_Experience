# The destinations map: an equirectangular view of the Alps; scripts/map.py draws its background in the same frame.
MAP_BOX = (5.55, 44.95, 13.95, 48.65)   # west, south, east, north, in degrees
MAP_W = 1000
_MAP_K = math.cos(math.radians(46.8))
_MAP_SCALE = MAP_W / ((MAP_BOX[2] - MAP_BOX[0]) * _MAP_K)
MAP_H = round((MAP_BOX[3] - MAP_BOX[1]) * _MAP_SCALE)


def map_xy(lat, lon):
    return (lon - MAP_BOX[0]) * _MAP_K * _MAP_SCALE, (MAP_BOX[3] - lat) * _MAP_SCALE


def distance(p, q):
    la1, lo1, la2, lo2 = map(math.radians, (p['lat'], p['lon'], q['lat'], q['lon']))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(h))


def nearest(place, n=3):
    others = [q for q in PLACES if q['slug'] != place['slug']]
    return sorted(others, key=lambda q: distance(place, q))[:n]


def enquire_url(destination=None, stay=None, interest=None, house=None, kind=None):
    """The enquiry page with the form filled in. Every value is URL-encoded and the result is ready for an
    attribute: /enquire/?destination=megeve&amp;stay=chalets-megeve&amp;house=Chalet%20141&amp;type=chalet"""
    q = [(k, v) for k, v in (('destination', destination), ('stay', stay), ('house', house), ('type', kind),
                             ('interest', interest)) if v]
    return localized('/enquire/') + ('?' + '&amp;'.join(f'{k}={quote(str(v), safe="")}' for k, v in q) if q else '')


