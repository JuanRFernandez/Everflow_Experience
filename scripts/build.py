def validate():
    problems = []
    slugs = [p['slug'] for p in PLACES] + [p['slug'] for p in PARTNERS] + [x['slug'] for x in EXPERIENCES]
    for s in set(slugs):
        if slugs.count(s) > 1:
            problems.append(f'slug used twice: {s}')
    for p in PLACES:
        if p['country'] not in COUNTRY:
            problems.append(f'place {p["slug"]}: unknown country {p["country"]}')
        im = p.get('image') or {}
        if im.get('license') and not all(im.get(k) for k in ('credit', 'source_url', 'license_url')):
            problems.append(f'place {p["slug"]}: a freely licensed photo needs credit (author), source_url and license_url')
    for p in PARTNERS:
        if p['place'] not in PLACE:
            problems.append(f'partner {p["slug"]}: unknown place {p["place"]}')
        if p.get('photos') and not p.get('credit'):
            problems.append(f'partner {p["slug"]}: photos without a credit line')
        for c in partner_credits(p):
            if 'everflow' in c.lower():
                problems.append(f'partner {p["slug"]}: a credit line names EverFlow; photos are credited to their owner')
    if problems:
        raise BuildError('\n'.join(problems))


