def types_of(x):
    """A stay's types, the main one first: "chalet", or ["hotel", "chalet"] for a hotel with a chalet."""
    kind = x.get('type') or []
    return [kind] if isinstance(kind, str) else list(kind)


def stay_types(p, r=None):
    """The types of one house (r), of a hotel, or of all the houses of a collection."""
    if r is not None:
        return types_of(r)
    if p.get('residences'):
        found = {k for h in p['residences'] for k in types_of(h)}
        return [k for k in STAY_TYPES if k in found]
    return types_of(p)


def stays():
    """Every stay of "Where to stay", in the order of content/partners.json: a hotel, or each house of a collection."""
    return [(p, r) for p in PARTNERS for r in (p.get('residences') or [None])]


def number(v):
    """1000 -> 1,000 (1.000 in Spanish and Portuguese); 12–16 and "about 800" keep their form."""
    sep = ',' if LANG == 'en' else '.'
    return re.sub(r'\d{4,}', lambda m: f'{int(m.group(0)):,}'.replace(',', sep), str(v))


def facts_row(x):
    """Guests · Bedrooms · Bathrooms · m²: the figures a stay states, the others left out."""
    items = []
    for key, one, many in COUNTS:
        if x.get(key):
            items.append(ui(one) if str(x[key]) == '1' else ui(many, n=number(x[key])))
    if x.get('size_m2'):
        size = str(x['size_m2'])
        items.append((ui('about {n}', n=number(size[6:])) if size.startswith('about ') else number(size)) + ' m²')
    return '<ul class="card-facts">' + ''.join(f'<li>{e(s)}</li>' for s in items) + '</ul>' if items else ''


def chips(x, limit):
    """The way to the slopes, then the highlights of a stay, as small labels."""
    items = ([x['ski_access']] if x.get('ski_access') else []) + list(x.get('highlights', []))
    return '<ul class="chips">' + ''.join(f'<li class="chip">{e(tr(s))}</li>' for s in items[:limit]) + '</ul>' if items else ''


def enquiry(p, r=None):
    """(address, label) of the button that opens the enquiry with this stay filled in: the house and its type,
    the hotel and its type, or, for a whole collection, the place and the collection."""
    if r is None and p.get('residences'):
        return enquire_url(p['place'], p['slug']), ui('Plan a stay here')
    kinds = stay_types(p, r)
    house = r['name'] if r is not None else None
    if len(kinds) > 1:  # a hotel with a chalet, a chalet of apartments: the guest says which in the form
        return enquire_url(p['place'], p['slug'], house=house), ui('Enquire about this stay')
    return enquire_url(p['place'], p['slug'], house=house, kind=kinds[0]), ui(ENQUIRE[kinds[0]])


def enquire_link(p, r=None):
    href, label = enquiry(p, r)
    name = r['name'] if r is not None else p['name']
    return (f'<a class="button button--small button--ghost card-enquire" href="{href}">{e(label)}'
            f'<span class="visually-hidden">: {e(name)}</span></a>')


