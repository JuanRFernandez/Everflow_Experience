def breadcrumb(items):
    lis = []
    for i, (label, href) in enumerate(items):
        if i == len(items) - 1:
            lis.append(f'<li aria-current="page">{e(label)}</li>')
        else:
            lis.append(f'<li><a href="{href}">{e(label)}</a></li>')
    return f'<nav class="breadcrumb" aria-label="Breadcrumb"><ol>{"".join(lis)}</ol></nav>'


def page_head(eyebrow_text, h1, lead=None, actions='', crumbs=None):
    crumbs_html = breadcrumb(crumbs) if crumbs else ''
    lead_html = f'<p class="lead">{t(lead)}</p>' if lead else ''
    actions_html = f'<div class="actions">{actions}</div>' if actions else ''
    return f'''<section class="page-head">
  <div class="wrap">
    {crumbs_html}
    {eyebrow(eyebrow_text)}
    <h1>{e(h1)}</h1>
    {lead_html}
    {actions_html}
  </div>
</section>'''


