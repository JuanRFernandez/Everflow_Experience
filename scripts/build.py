def validate():
    problems = []
    slugs = [p['slug'] for p in PLACES] + [p['slug'] for p in PARTNERS] + [x['slug'] for x in EXPERIENCES]
    for s in set(slugs):
        if slugs.count(s) > 1:
            problems.append(f'slug used twice: {s}')
    for s in FEATURED:
        if s not in PLACE:
            problems.append(f'destinations.json "featured": unknown destination {s}')
    for p in PLACES:
        if p['country'] not in COUNTRY:
            problems.append(f'place {p["slug"]}: unknown country {p["country"]}')
        im = p.get('image') or {}
        if im.get('license') and not all(im.get(k) for k in ('credit', 'source_url', 'license_url')):
            problems.append(f'place {p["slug"]}: a freely licensed photo needs credit (author), source_url and license_url')
    for p in PARTNERS:
        if p['place'] not in PLACE:
            problems.append(f'partner {p["slug"]}: unknown place {p["place"]}')
        if p.get('photos') and not p.get('credit'):
            problems.append(f'partner {p["slug"]}: photos without a credit line')
        for c in partner_credits(p):
            if 'everflow' in c.lower():
                problems.append(f'partner {p["slug"]}: a credit line names EverFlow; photos are credited to their owner')
        houses = p.get('residences', [])
        ids = [slugify(r['name']) for r in houses]
        for x, where in [(p, f'partner {p["slug"]}')] + [(r, f'partner {p["slug"]}, house {r["name"]}') for r in houses]:
            kind = x.get('type')
            kinds = [kind] if isinstance(kind, str) else kind if isinstance(kind, list) else None
            if (x is not p or not houses) and (not kinds or not all(isinstance(k, str) and k in STAY_TYPES for k in kinds)):
                problems.append(f'{where}: "type" must be {", ".join(STAY_TYPES)} or a list of them')
            for key, kind_of, what in (('kind', str, 'a short text'), ('ski_access', str, 'a short text'),
                                       ('renderings', bool, 'true or false'), ('card', str, 'a sentence'), ('about', str, 'a text')):
                if key in x and not isinstance(x[key], kind_of):
                    problems.append(f'{where}: "{key}" is {what}')
            marks = x.get('highlights', [])
            if not isinstance(marks, list) or not all(isinstance(m, str) for m in marks):
                problems.append(f'{where}: "highlights" is a list of short texts')
            elif len(marks) > 4:
                problems.append(f'{where}: at most 4 highlights')
            elif x is p and not houses and len(marks) + bool(x.get('ski_access')) > 3:
                problems.append(f'{where}: a hotel card shows three labels (the way to the slopes and the highlights); '
                                f'keep only those it shows')
            for key in ('guests', 'bedrooms', 'bathrooms', 'size_m2'):
                if key in x and not FIGURE.match(str(x[key])):
                    problems.append(f'{where}: "{key}" is a number, a range (12–16) or "about 800"')
            if x is not p and not x.get('card'):
                problems.append(f'{where}: a house needs its one-sentence "card"')
        for i in set(ids):
            if ids.count(i) > 1:
                problems.append(f'partner {p["slug"]}: two houses share the id {i}')
    for g in GUIDES:
        where = f'guide {g["slug"]}'
        im = g['image']
        if not (PLACE.get(im.get('place'), {}).get('image') or im.get('experience') in EXPERIENCE or (im.get('src') and im.get('alt'))):
            problems.append(f'{where}: the image names neither a destination with a photo, an experience, nor its own src and alt')
        if g.get('interest') and g['interest'] not in EXPERIENCE:
            problems.append(f'{where}: unknown experience {g["interest"]}')
        named = list(g.get('related', []))
        for s in g['sections']:
            named += [slug for slug, _ in s.get('places', [])]
            if s.get('image') and not PLACE.get(s['image'].get('place'), {}).get('image'):
                problems.append(f'{where}: section "{s["h2"]}" names a destination without a photo')
            for slug in s.get('stays', []):
                if slug not in PARTNER:
                    problems.append(f'{where}: unknown partner {slug}')
        for slug in named:
            if slug not in PLACE:
                problems.append(f'{where}: unknown destination {slug}')
    if problems:
        raise BuildError('\n'.join(problems))


def render_translated():
    """The pages that exist in every language, in the language being rendered."""
    out = {'index.html': home(), 'destinations/index.html': destinations_index(), 'enquire/index.html': enquire_page()}
    for p in PLACES:
        out[f'destinations/{p["slug"]}/index.html'] = place_page(p)
    return {out_path(k): v for k, v in out.items()}


def render_all():
    global LANG
    validate()
    MISSING.clear()
    USED.clear()
    LANG = 'en'
    out = render_translated()
    out.update({'stay/index.html': stay_index(), 'experiences/index.html': experiences_page(),
                'about/index.html': about_page(), '404.html': not_found(),
                'impressum.html': legal('impressum'), 'datenschutz.html': legal('datenschutz')})
    for p in PARTNERS:
        out[f'stay/{p["slug"]}/index.html'] = partner_page(p)
    out['guides/index.html'] = guides_index()
    for g in GUIDES:
        out[f'guides/{g["slug"]}/index.html'] = guide_page(g)
    for code in LANGS:
        if code != 'en':
            LANG = code
            try:
                out.update(render_translated())
            finally:
                LANG = 'en'
    indexable = [p for p in out if p not in ('404.html', 'impressum.html', 'datenschutz.html')]
    out['sitemap.xml'] = sitemap(sorted(indexable, key=lambda p: (p != 'index.html', p)))
    out['robots.txt'] = ('User-agent: *\nAllow: /\n' + ''.join(f'Disallow: {x}\n' for x in ROBOTS_OFF)
                         + f'\nSitemap: {SITE["url"]}/sitemap.xml\n')
    return out


def generated_on_disk():
    """Every file this script wrote before: pages carrying the marker, plus sitemap.xml and robots.txt."""
    found = []
    for name in ('sitemap.xml', 'robots.txt'):
        if os.path.isfile(os.path.join(ROOT, name)):
            found.append(name)
    for dp, dirs, files in os.walk(ROOT):
        rel = os.path.relpath(dp, ROOT).replace(os.sep, '/')
        if rel == '.':
            dirs[:] = [d for d in dirs if d in LEGACY_DIRS]
        for f in files:
            if f.endswith('.html'):
                path = f if rel == '.' else f'{rel}/{f}'
                with open(os.path.join(dp, f), encoding='utf-8', errors='replace') as fh:
                    if MARK in fh.read(400):
                        found.append(path)
    return found


def main(argv):
    try:
        out = render_all()
    except BuildError as err:
        print('STOP', err)
        return 2
    if '--missing' in argv:
        target = argv[argv.index('--missing') + 1]
        with open(target, 'w', encoding='utf-8', newline='\n') as f:
            json.dump({k: sorted(v) for k, v in sorted(MISSING.items())}, f, ensure_ascii=False, indent=1)
        print(f'{sum(len(v) for v in MISSING.values())} missing translations written to {target}')
        return 0
    for code, texts in sorted(MISSING.items()):
        print(f'WARN {len(texts)} texts have no {code} translation yet (content/i18n/{code}.json)')
    for code in sorted(I18N):
        left = set(I18N[code]) - USED.get(code, set())
        if left:
            print(f'WARN {len(left)} texts in content/i18n/{code}.json are no longer on any page')
    stale = [p for p in generated_on_disk() if p not in out]
    if '--check' in argv:
        bad = []
        for path, text in out.items():
            full = os.path.join(ROOT, path)
            if not os.path.isfile(full) or open(full, encoding='utf-8', newline='').read() != text:
                bad.append(path)
        for p in bad:
            print(f'FAIL {p} is not what content/ gives: run python scripts/build.py')
        for p in stale:
            print(f'FAIL {p} was generated before but no longer is: run python scripts/build.py')
        return 1 if bad or stale else 0
    for path, text in out.items():
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full) or ROOT, exist_ok=True)
        with open(full, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    for p in stale:
        os.remove(os.path.join(ROOT, p))
        print('removed', p)
    print(f'{len(out)} files written')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
