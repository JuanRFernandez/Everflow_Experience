MAP_COUNTRIES = {'germany': (48.42, 9.4), 'austria': (47.02, 13.3), 'switzerland': (47.17, 7.55), 'france': (45.12, 6.3),
                 'italy': (45.27, 9.9)}       # where each country's name sits on the map
