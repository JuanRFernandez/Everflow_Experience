def load_i18n(code):
    path = os.path.join(ROOT, 'content', 'i18n', code + '.json')
    if not os.path.isfile(path):
        return {}
    with open(path, encoding='utf-8') as f:
        return json.load(f)


I18N = {code: load_i18n(code) for code in LANGS if code != 'en'}
LANG = 'en'      # the language being rendered; render_all() switches it
MISSING = {}     # language -> English texts that have no translation yet
USED = {}        # language -> English texts a page used; the others in content/i18n/ are left over


def tr(s):
    """The text in the language being rendered; English, and noted, when there is no translation yet.
    A text without words (a number, 3–4) stays as it is."""
    if LANG == 'en' or not re.search('[A-Za-z]', s or ''):
        return s
    out = I18N[LANG].get(s)
    if out is None:
        MISSING.setdefault(LANG, set()).add(s)
        return s
    USED.setdefault(LANG, set()).add(s)
    return out


def tro(s):
    """Optional translation, for names: most stay as they are (Zermatt), a few change (Munich)."""
    if LANG == 'en' or s not in I18N[LANG]:
        return s
    USED.setdefault(LANG, set()).add(s)
    return I18N[LANG][s]


def ui(s, **kw):
    return tr(s).format(**kw) if kw else tr(s)


def translated(path):
    """True for the pages that exist in every language: home, destinations, enquiry."""
    base = path.split('?')[0].split('#')[0]
    return base == '/' or base.startswith('/destinations/') or base.startswith('/enquire/')


def localized(path):
    """An internal address in the language being rendered, where that page exists in it."""
    if LANG == 'en' or not path.startswith('/') or not translated(path):
        return path
    return LANGS[LANG]['prefix'] + path


def out_path(path):
    """Where a page of the language being rendered is written: es/destinations/index.html."""
    return path if LANG == 'en' else f'{LANG}/{path}'


# ---------------------------------------------------------------- text helpers

def lower_first(s):
    """'Summer in the Alps' -> 'summer in the Alps': only the first letter changes."""
    return s[:1].lower() + s[1:]


def e(s):
    """Escape text for an HTML text node."""
    return html.escape(str(s), quote=False)


def a(s):
    """Escape text for an HTML attribute value."""
    return html.escape(str(s), quote=True)


LINK = re.compile(r'\[([^\]]+)\]\(((?:/|https://|mailto:)[^)\s]*)\)')


def t(s):
    """Text with [label](url) links; everything else is escaped."""
    out, pos = [], 0
    for m in LINK.finditer(s):
        out.append(e(s[pos:m.start()]))
        url = localized(m.group(2))
        rel = ' rel="noopener"' if url.startswith('https://') else ''
        out.append(f'<a href="{a(url)}"{rel}>{e(m.group(1))}</a>')
        pos = m.end()
    out.append(e(s[pos:]))
    return ''.join(out)


def coords(lat, lon):
    return f'{abs(lat):.2f}°{"N" if lat >= 0 else "S"}, {abs(lon):.2f}°{"E" if lon >= 0 else "W"}'


def slugify(name):
    """Chalet Cham Lou'Ka -> chalet-cham-louka: an id for a link to one house."""
    s = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '-', re.sub(r"['’]", '', s)).strip('-')


def num(i):
    return f'{i:02d}'


def url_of(path):
    """Public URL of an output file: index.html -> /, about/index.html -> /about/."""
    if path == 'index.html':
        return '/'
    if path.endswith('/index.html'):
        return '/' + path[:-len('index.html')]
    return '/' + path


# ---------------------------------------------------------------- images

def image_size(path):
    with open(path, 'rb') as f:
        head = f.read(32)
    if head[:8] == b'\x89PNG\r\n\x1a\n':
        return struct.unpack('>II', head[16:24])
    if head[:4] == b'RIFF' and head[8:12] == b'WEBP':
        kind = head[12:16]
        if kind == b'VP8 ':
            w, h = struct.unpack('<HH', head[26:30])
            return w & 0x3FFF, h & 0x3FFF
        if kind == b'VP8L':
            bits = int.from_bytes(head[21:25], 'little')
            return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
        if kind == b'VP8X':
            return 1 + int.from_bytes(head[24:27], 'little'), 1 + int.from_bytes(head[27:30], 'little')
    raise BuildError(f'unknown image format: {path}')


def variants(base):
    """[(width, height, url)] of the WebP files written by scripts/photos.py for one image."""
    folder, stem = os.path.split(base)
    full = os.path.join(ROOT, folder)
    if not os.path.isdir(full):
        raise BuildError(f'image folder missing: {folder}')
    found = {}
    for f in sorted(os.listdir(full)):
        if re.fullmatch(re.escape(stem) + r'-\d+\.webp', f):
            w, h = image_size(os.path.join(full, f))
            found.setdefault(w, (w, h, f'{folder}/{f}'))
    if not found:
        raise BuildError(f'no image files for {base} (run scripts/photos.py)')
    return [found[w] for w in sorted(found)]


def img(base, alt, sizes, cls='', eager=False):
    v = variants(base)
    w, h, url = v[-1]
    srcset = ', '.join(f'/{u} {vw}w' for vw, _, u in v)
    load = ' fetchpriority="high"' if eager else ' loading="lazy" decoding="async"'
    klass = f' class="{cls}"' if cls else ''
    return (f'<img src="/{url}" srcset="{srcset}" sizes="{a(sizes)}" width="{w}" height="{h}"'
            f' alt="{a(alt)}"{klass}{load}>')


def credit_text(credit):
    """The line under a photo: "© Owner"; a courtesy line ("Photo courtesy of the owner") stands without "©"."""
    if credit.startswith('Photo courtesy'):
        return tr(credit)
    return credit if credit.startswith('©') else f'© {credit}'


def caption(credit, image=None, links=True):
    """The credit under a photo: "© Owner" (or a courtesy line), or for a freely licensed photo "© Author · Licence",
    linked to the photo's source page and to the licence (not inside cards, which are one big link)."""
    image = image or {}
    if not image.get('license'):
        return e(credit_text(credit))
    if links:
        author = f'© <a href="{a(image["source_url"])}" rel="noopener">{e(credit)}</a>'
        lic = f'<a href="{a(image["license_url"])}" rel="noopener">{e(image["license"])}</a>'
        return f'{author} · {lic}'
    return f'{e(credit_text(credit))} · {e(image["license"])}'


def figure(base, alt, sizes, credit=None, cls='', eager=False, image=None, links=True):
    cap = f'<figcaption class="credit">{caption(credit, image, links)}</figcaption>' if credit else ''
    klass = f' class="{cls}"' if cls else ''
    return f'<figure{klass}>{img(base, alt, sizes, eager=eager)}{cap}</figure>'


def asset_url(rel):
    with open(os.path.join(ROOT, rel), 'rb') as f:
        digest = hashlib.sha1(f.read()).hexdigest()[:8]
    return f'/{rel}?v={digest}'


